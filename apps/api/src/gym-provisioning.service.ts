import { randomUUID } from 'node:crypto';
import { promisify } from 'node:util';
import { execFile } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';
import {
  ConflictException,
  Injectable,
  Logger,
  ServiceUnavailableException,
  type OnApplicationShutdown,
} from '@nestjs/common';
import argon2 from 'argon2';
import pg from 'pg';
import { DatabaseService } from './database.service.js';
import { Prisma } from './generated/master/client.js';
import { normalizeIdentityEmail } from './identity/email.js';
import { AdmissionUnavailable } from './bounded-tenant-leases.js';
import { databasePoolConfig } from './database-pool-config.js';
import { SingleAdmission } from './single-admission.js';

const execFileAsync = promisify(execFile);
const repoRoot = fileURLToPath(new URL('../../../', import.meta.url));

type CreateGymInput = {
  name: string;
  slug: string;
  ownerEmail: string;
  ownerPassword: string;
};

@Injectable()
export class GymProvisioningService implements OnApplicationShutdown {
  private readonly logger = new Logger(GymProvisioningService.name);
  private readonly admission = new SingleAdmission();
  private pool?: pg.Pool;

  constructor(private readonly database: DatabaseService) {}

  async create(input: CreateGymInput) {
    try {
      return await this.admission.run(() => this.createAdmitted(input));
    } catch (error) {
      if (error instanceof AdmissionUnavailable) {
        throw new ServiceUnavailableException({
          statusCode: 503,
          message: 'Gym provisioning is temporarily unavailable',
          retryable: true,
        });
      }
      throw error;
    }
  }

  private provisioningPool(): pg.Pool {
    if (this.pool) return this.pool;
    const pool = new pg.Pool(databasePoolConfig(process.env.PROVISION_DATABASE_URL, 'provisioning'));
    pool.on('error', () => this.logger.warn('Provisioning database connection failed'));
    this.pool = pool;
    return pool;
  }

  private async createAdmitted(input: CreateGymInput) {
    const master = this.database.master;
    const ownerEmail = normalizeIdentityEmail(input.ownerEmail);
    const [existingGym, existingOwner] = await Promise.all([
      master.gym.findUnique({ where: { slug: input.slug }, select: { id: true } }),
      master.user.findUnique({
        where: { email: ownerEmail },
        select: { id: true },
      }),
    ]);
    if (existingGym) throw new ConflictException('Gym slug already exists');
    if (existingOwner) throw new ConflictException('Owner email already exists');

    const provisionUrl = process.env.PROVISION_DATABASE_URL;
    const tenantBaseUrl = process.env.TENANT_DATABASE_URL;
    if (!provisionUrl || !tenantBaseUrl) {
      throw new ServiceUnavailableException('Gym provisioning is not configured');
    }

    const passwordHash = await argon2.hash(input.ownerPassword, {
      type: argon2.argon2id,
    });
    const databaseName = `gymos_${randomUUID().replaceAll('-', '')}`;
    const tenantUrl = new URL(tenantBaseUrl);
    tenantUrl.pathname = `/${databaseName}`;
    let gymId: string | undefined;

    try {
      const gym = await master.gym.create({
        data: {
          name: input.name,
          slug: input.slug,
          databaseName,
          status: 'PROVISIONING',
        },
      });
      gymId = gym.id;

      const admin = await this.provisioningPool().connect();
      try {
        // databaseName is generated by the server, never taken from request data.
        await admin.query(`CREATE DATABASE "${databaseName}"`);
      } finally {
        admin.release();
      }

      const prismaCli = join(repoRoot, 'node_modules/prisma/build/index.js');
      await execFileAsync(
        process.execPath,
        [prismaCli, 'migrate', 'deploy', '--config', './prisma.tenant.config.ts'],
        {
          cwd: repoRoot,
          env: { ...process.env, TENANT_DATABASE_URL: tenantUrl.toString() },
          maxBuffer: 1024 * 1024,
        },
      );

      await master.$transaction(async (tx) => {
        const owner = await tx.user.create({
          data: { email: ownerEmail, passwordHash },
        });
        await tx.gymAccess.create({
          data: { userId: owner.id, gymId: gym.id, role: 'OWNER', linkStatus: 'ACTIVE' },
        });
        await tx.theme.create({ data: { gymId: gym.id } });
        await tx.gym.update({
          where: { id: gym.id },
          data: { status: 'ACTIVE' },
        });
      });

      return { id: gym.id, slug: gym.slug, name: gym.name, status: 'ACTIVE' };
    } catch (error) {
      if (gymId) {
        await master.gym.update({
          where: { id: gymId },
          data: { status: 'FAILED' },
        });
      }
      if (
        error instanceof Prisma.PrismaClientKnownRequestError &&
        error.code === 'P2002'
      ) {
        throw new ConflictException('Gym slug or owner email already exists');
      }
      this.logger.error('Gym provisioning failed', error);
      throw new ServiceUnavailableException('Gym provisioning failed');
    }
  }

  async onApplicationShutdown(): Promise<void> {
    await this.admission.drain();
    if (this.pool) await this.pool.end();
  }
}
